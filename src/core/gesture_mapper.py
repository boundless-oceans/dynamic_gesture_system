# `guide`（✌️）撞的是动态的「双指指向 / 双指双击 → 旋转模型」，而那个动作
# **只在 3D 页上有效**。所以 3D 页把 ✌️ 归动态模型，静态这边当作弃权。
#
# ⚠️ 别的页面上动态那个手势本来就是空转，所以只在 3D 页让。
